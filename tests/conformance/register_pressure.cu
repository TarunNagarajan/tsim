int main() {
  constexpr int count = 64, threads = 32;
  std::vector<int> input(count), output(threads * count);
  for (int i = 0; i < count; ++i) input[i] = i - 17;
  int *device_input, *device_output;
  CUDA(cudaMalloc(&device_input, count * sizeof(int)));
  CUDA(cudaMalloc(&device_output, threads * count * sizeof(int)));
  CUDA(cudaMemcpy(device_input, input.data(), count * sizeof(int), cudaMemcpyHostToDevice));
  register_pressure<<<1, threads>>>(device_input, device_output);
  CUDA(cudaGetLastError()); CUDA(cudaDeviceSynchronize());
  CUDA(cudaMemcpy(output.data(), device_output, threads * count * sizeof(int), cudaMemcpyDeviceToHost));
  CUDA(cudaFree(device_input)); CUDA(cudaFree(device_output));
  for (int lane = 0; lane < threads; ++lane)
    for (int i = 0; i < count; ++i)
      if (output[lane * count + i] != input[i]) { std::fprintf(stderr, "register_pressure mismatch lane=%d i=%d\n", lane, i); return 1; }
  std::printf("PASS register_pressure values=%d lanes=%d\n", count, threads);
}
